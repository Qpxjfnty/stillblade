import { chromium } from 'playwright';
import assert from 'node:assert/strict';
import { mkdir, readFile, writeFile } from 'node:fs/promises';

const url = process.env.QA_URL || 'http://127.0.0.1:4173/';
const output = process.env.QA_OUTPUT || 'output/playwright';
const SAVE_KEY = 'stillblade.combat.v1';
await mkdir(output, { recursive: true });
const report = {
  url, startedAt: new Date().toISOString(), cases: [],
  scope: 'Actual Chromium UI interactions for keyboard, focus, cancellation, persistence and payment. Separate from responsive/browser matrix.',
  fixturePolicy: 'Fresh-soul payment is reached through actual UI moves. Reserve payment uses a saved state generated by replaying the verified default victory through the engine, then starts a new browser context with that fixture. Only fixture preparation invokes dispatch.',
  limitations: 'Automated desktop keyboard/pointer checks; not assistive-technology or physical-device certification.',
};
const browser = await chromium.launch({ headless: true });
const state = page => page.evaluate(() => window.__STILLBLADE__.getState());
const boardCell = (page, point) => page.locator(`[data-cell="${point.x},${point.y}"]`);
let baseline;

async function waitReady(page) {
  await page.waitForFunction(() => !!window.__STILLBLADE__);
  await page.locator('[data-cell="5,4"]').waitFor();
}
async function pendingSlip(page) {
  await page.locator('body').click({ position: { x: 4, y: 4 } });
  await page.keyboard.press('1');
  assert.equal(await page.locator('#action-slip').getAttribute('class').then(c => c.includes('active')), true);
  const current = (await page.evaluate(() => document.activeElement?.getAttribute('data-cell'))).split(',').map(Number);
  while (current[0] !== 5) { await page.keyboard.press(current[0] < 5 ? 'ArrowRight' : 'ArrowLeft'); current[0] += current[0] < 5 ? 1 : -1; }
  while (current[1] !== 6) { await page.keyboard.press(current[1] < 6 ? 'ArrowDown' : 'ArrowUp'); current[1] += current[1] < 6 ? 1 : -1; }
  assert.equal(await page.evaluate(() => document.activeElement?.getAttribute('data-cell')), '5,6');
  await page.keyboard.press('Space');
  assert.equal(await page.locator('#confirm').isEnabled(), true);
  assert.equal(await page.evaluate(() => document.activeElement?.id), 'confirm');
}
async function uiCommand(page, command) {
  const before = await state(page);
  const expected = await page.evaluate(c => window.__STILLBLADE__.preview(c), command);
  assert.equal(expected.ok, true, expected.error);
  await page.locator(`[data-action="${command.kind}"]`).click();
  if (command.kind === 'parry' || command.kind === 'sweep') {
    await boardCell(page, command.to || before.player).click();
    for (const id of command.targets || [command.target]) await boardCell(page, before.enemies.find(e => e.id === id)).click();
  } else if (command.to) await boardCell(page, command.to).click();
  else if (command.target) await boardCell(page, before.enemies.find(e => e.id === command.target)).click();
  assert.deepEqual(await state(page), before, 'Preview advanced time');
  await page.locator('#confirm').click();
  assert.deepEqual(await state(page), expected.state, 'Actual UI action differs from forecast');
}
async function run(name, callback, init) {
  const context = await browser.newContext({ viewport: { width: 1440, height: 1000 }, reducedMotion: 'reduce' });
  if (init) await init(context);
  const page = await context.newPage();
  page.setDefaultTimeout(8000);
  const errors = [];
  page.on('pageerror', e => errors.push(e.message));
  page.on('console', m => { if (m.type() === 'error') errors.push(m.text()); });
  const result = { name, status: 'running' };
  try {
    await page.goto(url);
    await waitReady(page);
    await callback(page, result);
    assert.deepEqual(errors, [], 'Browser runtime errors');
    result.status = 'passed';
  } catch (error) {
    result.status = 'failed'; result.error = String(error); result.errors = errors;
    await page.screenshot({ path: `${output}/interaction-${name}-failure.png`, fullPage: true }).catch(() => {});
    process.exitCode = 1;
  } finally {
    report.cases.push(result);
    await writeFile(`${output}/interaction-report.json`, JSON.stringify(report, null, 2));
    console.log(JSON.stringify(result));
    await context.close();
  }
}

await run('keyboard-commit-and-reload', async (page, result) => {
  baseline = await state(page);
  await pendingSlip(page);
  assert.deepEqual(await state(page), baseline);
  await page.screenshot({ path: `${output}/interaction-keyboard-preview.png`, fullPage: true });
  const predicted = await page.evaluate(() => window.__STILLBLADE__.preview({ kind: 'slip', to: { x: 5, y: 6 } }));
  await page.keyboard.press('Enter');
  assert.deepEqual(await state(page), predicted.state);
  assert.equal((await state(page)).beat, 1);
  const saved = await state(page);
  assert.deepEqual(await page.evaluate(key => JSON.parse(localStorage.getItem(key)), SAVE_KEY), saved);
  await page.reload();
  await waitReady(page);
  assert.deepEqual(await state(page), saved);
  result.beatsAfterKeyboardCommitAndReload = saved.beat;
});

await run('escape-cancel-and-noncommit-controls', async page => {
  const initial = await state(page);
  await pendingSlip(page);
  await page.keyboard.press('Escape');
  assert.equal(await page.locator('#confirm').isDisabled(), true);
  assert.deepEqual(await state(page), initial);
  await pendingSlip(page);
  await page.locator('#cancel').click();
  assert.equal(await page.locator('#confirm').isDisabled(), true);
  assert.deepEqual(await state(page), initial);
  await pendingSlip(page);
  for (const [selector, dialogName] of [['#help', 'Field guide'], ['#restart', 'Restart encounter']]) {
    await page.locator(selector).focus();
    await page.keyboard.press('Enter');
    await page.getByRole('dialog', { name: dialogName }).waitFor();
    assert.deepEqual(await state(page), initial, `Enter on ${selector} committed the pending combat action`);
    await page.keyboard.press('Escape');
    assert.equal(await page.getByRole('dialog').count(), 0);
    assert.equal(await page.locator('#confirm').isEnabled(), true, 'Closing modal lost the pending preview');
  }
  await page.locator('#cancel').focus();
  await page.keyboard.press('Enter');
  assert.equal(await page.locator('#confirm').isDisabled(), true);
  assert.deepEqual(await state(page), initial);
});

await run('modal-focus-loop', async page => {
  await page.locator('#help').focus();
  await page.keyboard.press('Enter');
  await page.getByRole('dialog', { name: 'Field guide' }).waitFor();
  assert.equal(await page.locator('main').getAttribute('inert'), '');
  const focusable = page.locator('.modal button, .modal [href], .modal input, .modal select, .modal summary');
  await focusable.last().focus();
  await page.keyboard.press('Tab');
  assert.equal(await focusable.first().evaluate(el => el === document.activeElement), true, 'Forward Tab did not wrap');
  await page.keyboard.press('Shift+Tab');
  assert.equal(await focusable.last().evaluate(el => el === document.activeElement), true, 'Reverse Tab did not wrap');
  for (let n = 0; n < 12; n++) {
    await page.keyboard.press('Tab');
    assert.equal(await page.evaluate(() => !!document.activeElement?.closest('.modal')), true, 'Tab escaped modal');
  }
  await page.screenshot({ path: `${output}/interaction-modal-focus.png`, fullPage: true });
  await page.keyboard.press('Escape');
  assert.equal(await page.locator('#help').evaluate(el => el === document.activeElement), true, 'Modal failed to return focus');
});

for (const [name, saved] of [['malformed-save-fallback', '{broken-json'], ['old-save-fallback', JSON.stringify({ ...baseline, version: 0 })]]) {
  await run(name, async page => {
    assert.deepEqual(await state(page), baseline, 'Invalid saved state did not fall back to a fresh arena');
    await pendingSlip(page);
    await page.keyboard.press('Enter');
    assert.equal((await state(page)).beat, 1);
  }, context => context.addInitScript(({ key, value }) => localStorage.setItem(key, value), { key: SAVE_KEY, value: saved }));
}

const invalidEnemySaves = [
  ['excessive-max-hp-save-fallback', s => { s.enemies[0].maxHp = 1000; }],
  ['zero-max-guard-save-fallback', s => { s.enemies[0].maxGuard = 0; }],
  ['fractional-exposure-save-fallback', s => { s.enemies[0].exposure = 0.5; }],
  ['overlapping-actor-save-fallback', s => { s.enemies[0].x = s.player.x; s.enemies[0].y = s.player.y; }],
  ['duplicate-enemy-id-save-fallback', s => { s.enemies[1].id = s.enemies[0].id; }],
  ['invalid-enemy-kind-save-fallback', s => { s.enemies[0].kind = 'toString'; }],
];
for (const [name, alter] of invalidEnemySaves) {
  const invalid = structuredClone(baseline);
  alter(invalid);
  await run(name, async page => {
    assert.deepEqual(await state(page), baseline, 'Invalid enemy state restored instead of a fresh encounter');
  }, context => context.addInitScript(({ key, value }) => localStorage.setItem(key, JSON.stringify(value)), { key: SAVE_KEY, value: invalid }));
}

