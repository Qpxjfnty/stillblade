await run('fresh-token-choice', async (page, result) => {
  await page.locator('#scenarios').click();
  await page.locator('[data-scenario="combo"]').click();
  for (const cmd of [{ kind: 'activate' }, { kind: 'lunge', target: 'A' }, { kind: 'bell', to: { x: 7, y: 6 } }, { kind: 'lunge', target: 'B' }, { kind: 'lunge', target: 'C' }]) await uiCommand(page, cmd);
  const before = await state(page);
  assert.equal(before.fresh.length, 2);
  const [oldest, newest] = before.fresh;
  await page.locator('#action-thread').click();
  await boardCell(page, { x: 7, y: 5 }).click();
  assert.equal(await page.locator(`[data-soul="${oldest.id}"]`).isChecked(), true);
  assert.equal(await page.locator(`[data-soul="${newest.id}"]`).isChecked(), false);
  await page.locator(`[data-soul="${oldest.id}"]`).uncheck();
  assert.equal(await page.locator('#confirm').isDisabled(), true, 'Underpaid spell can be committed');
  await page.locator(`[data-soul="${newest.id}"]`).check();
  assert.equal(await page.locator('#confirm').isEnabled(), true);
  assert.deepEqual(await state(page), before);
  const command = { kind: 'thread', to: { x: 7, y: 5 }, payment: { fresh: [newest.id], reserve: 0 } };
  const expected = await page.evaluate(c => window.__STILLBLADE__.preview(c), command);
  assert.equal(expected.ok, true, expected.error);
  await page.screenshot({ path: `${output}/interaction-fresh-payment.png`, fullPage: true });
  await page.locator('#confirm').click();
  assert.deepEqual(await state(page), expected.state);
  assert.deepEqual((await state(page)).fresh.map(s => s.id), [oldest.id]);
  result.fixture = 'Reached through five real UI commands from The perfect opening';
  result.consumed = newest.id;
  result.preserved = oldest.id;
});

// Prepare a reachable, conserved-resource fixture from the committed regression replay.
const winning = JSON.parse(await readFile(new URL('../tests/fixtures/winning-replay.json', import.meta.url), 'utf8'));
const prepContext = await browser.newContext();
const prepPage = await prepContext.newPage();
await prepPage.goto(url);
await waitReady(prepPage);
let reserveFixture;
let replayedCommands = 0;
for (const cmd of winning.commands) {
  const r = await prepPage.evaluate(c => window.__STILLBLADE__.dispatch(c), cmd);
  assert.equal(r.ok, true, r.error);
  replayedCommands++;
  if (r.state.phase === 'defense' && r.state.reserve >= 3) { reserveFixture = r.state; break; }
}
await prepContext.close();
assert.ok(reserveFixture, 'Verified replay did not produce a defensive reserve fixture');
await run('reserve-only-defensive-payment', async (page, result) => {
  assert.deepEqual(await state(page), reserveFixture, 'Valid fixture did not restore');
  const legal = await page.evaluate(() => window.__STILLBLADE__.getLegalCommands());
  const candidate = legal.find(c => c.kind === 'bell') || legal.find(c => c.kind === 'thread');
  assert.ok(candidate, 'No reserve spell legal in fixture');
  const command = { ...candidate, payment: { fresh: [], reserve: 3 } };
  const expected = await page.evaluate(c => window.__STILLBLADE__.preview(c), command);
  assert.equal(expected.ok, true, expected.error);
  await page.locator(`[data-action="${command.kind}"]`).click();
  await boardCell(page, command.to).click();
  assert.equal(await page.locator('[data-soul]').count(), 0, 'Defensive time offered fresh souls');
  assert.equal(await page.locator('#reserve-payment').inputValue(), '3');
  await page.locator('#reserve-payment').selectOption('0');
  assert.equal(await page.locator('#confirm').isDisabled(), true);
  await page.locator('#reserve-payment').selectOption('3');
  assert.equal(await page.locator('#confirm').isEnabled(), true);
  assert.deepEqual(await state(page), reserveFixture);
  await page.screenshot({ path: `${output}/interaction-reserve-payment.png`, fullPage: true });
  await page.locator('#confirm').click();
  assert.deepEqual(await state(page), expected.state);
  assert.equal((await state(page)).beat, reserveFixture.beat + 1);
  assert.equal((await state(page)).reserve, reserveFixture.reserve - 3);
  result.fixture = `Injected valid saved state generated by ${replayedCommands} engine-only replay commands; tested spell selection, payment and confirmation through UI`;
  result.spell = command.kind;
}, context => context.addInitScript(({ key, value }) => localStorage.setItem(key, JSON.stringify(value)), { key: SAVE_KEY, value: reserveFixture }));

report.finishedAt = new Date().toISOString();
await writeFile(`${output}/interaction-report.json`, JSON.stringify(report, null, 2));
await browser.close();
